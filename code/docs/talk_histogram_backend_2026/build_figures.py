def _load_manifest(root: Path) -> dict[str, Any]:
    return json.loads((root / "corpus_manifest.json").read_text(encoding="utf-8"))


def _load_edge_lengths_km(manifest: dict[str, Any]) -> np.ndarray:
    values: list[float] = []
    for graph in manifest["graphs"]:
        topology_path = ROOT / str(graph["topology_path"])
        topology = json.loads(topology_path.read_text(encoding="utf-8"))
        values.extend(float(edge["length_m"]) / 1000.0 for edge in topology["edges"])
    return np.asarray(values, dtype=float)


def _describe(values: Iterable[float]) -> dict[str, float]:
    ordered = np.sort(np.asarray(tuple(values), dtype=float))
    return {
        "min": float(ordered[0]),
        "median": float(statistics.median(ordered)),
        "mean": float(statistics.fmean(ordered)),
        "max": float(ordered[-1]),
    }


