def build_eve_strategy_heatmap() -> dict[str, Any]:
    """Render the tracked Eve-family masses with a readable turbo palette."""

    table_path = PAPER_RUN / "tables" / "eve_family_strategy.csv"
    with table_path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    case_order = [
        "short_disjoint",
        "medium_disjoint",
        "mixed_bottleneck",
        "long_composable",
    ]
    family_order = [
        "no_attack",
        "edge_dos",
        "edge_information_probe",
        "swap_denial",
        "memory_degradation",
        "repeater_memory_measure_Z",
        "repeater_memory_measure_X",
    ]
    family_labels = [
        "No attack",
        "Edge DoS",
        "Information probe",
        "Swap denial",
        "Memory degradation",
        "Memory measure Z",
        "Memory measure X",
    ]

    grouped: dict[tuple[str, str], dict[str, list[float]]] = {}
    for row in rows:
        key = (str(row["case_slug"]), str(row["attack_family"]))
        bucket = grouped.setdefault(key, {"learned": [], "oracle": []})
        bucket["learned"].append(float(row["learned_mass"]))
        bucket["oracle"].append(float(row["oracle_mass"]))

    matrices: dict[str, np.ndarray] = {}
    for metric in ("learned", "oracle"):
        matrices[metric] = np.asarray(
            [
                [
                    statistics.fmean(grouped[(case, family)][metric])
                    for family in family_order
                ]
                for case in case_order
            ],
            dtype=float,
        )

    fig, axes = plt.subplots(
        1,
        2,
        figsize=(13.5, 5.7),
        constrained_layout=True,
        sharey=True,
    )
    cmap = plt.get_cmap("turbo")
    image_artist = None
    for ax, metric, title in zip(
        axes,
        ("learned", "oracle"),
        ("Learned empirical play", "Post-hoc empirical oracle"),
    ):
        matrix = matrices[metric]
        image_artist = ax.imshow(matrix, vmin=0.0, vmax=1.0, cmap=cmap, aspect="auto")
        ax.set_title(title, fontsize=13, fontweight="bold", pad=9)
        ax.set_xticks(np.arange(len(family_labels)), family_labels, rotation=38, ha="right")
